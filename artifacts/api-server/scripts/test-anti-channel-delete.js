process.env.DATA_DIR = require("os").tmpdir() + "/acd-" + Date.now();
const assert = require("assert");
const acd = require("../utils/antiChannelDelete");

const g = "g1";
assert.strictEqual(acd.recordDeletion(g, "u", 0), false, "désactivé : jamais de déclenchement");
acd.system.setState(g, { enabled: true, config: { count: 3, seconds: 10, sanction: "kick", logChannelId: "c1" } });
assert.strictEqual(acd.recordDeletion(g, "u", 0), false);
assert.strictEqual(acd.recordDeletion(g, "u", 5000), false);
assert.strictEqual(acd.recordDeletion(g, "u", 9000), true, "3 en 10 s");
assert.strictEqual(acd.recordDeletion(g, "u", 9500), false, "compteur remis à zéro");
assert.strictEqual(acd.recordDeletion(g, "v", 0), false);
assert.strictEqual(acd.recordDeletion(g, "v", 11000), false);
assert.strictEqual(acd.recordDeletion(g, "v", 22000), false, "hors fenêtre");
const st = acd.system.setState(g, { config: { sanction: "nope", count: 0, lockServer: true } });
assert.strictEqual(st.config.sanction, "kick", "sanction invalide ignorée");
assert.strictEqual(st.config.count, 1, "borné à 1 minimum");
assert.strictEqual(st.config.lockServer, true);
assert.strictEqual(st.enabled, true);
console.log("ok");
